"""Export of numbers and tables into the LaTeX sources of the paper.

Every number quoted in Part 2 of the paper is produced by the code and
written to ``paper/generated``; the text refers to it through a macro, so
re-running an experiment updates the paper consistently.
"""
from __future__ import annotations

import json
import re

import numpy as np
import pandas as pd

from . import config as C


def _macro_name(prefix: str, key: str) -> str:
    words = re.split(r"[^A-Za-z0-9]+", f"{prefix} {key}")
    digits = {"0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four", "5": "Five",
              "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"}
    name = "".join(w[:1].upper() + w[1:] for w in words if w)
    return "".join(digits.get(ch, ch) for ch in name)


def fmt(x, nd: int = 3) -> str:
    if isinstance(x, (int, np.integer)):
        return f"{x:,}".replace(",", "\\,")
    if isinstance(x, (float, np.floating)):
        if not np.isfinite(x):
            return "--"
        if round(float(x), nd) == 0:
            x = 0.0                                     # no "-0.000"
        return f"{x:.{nd}f}".replace("-", "\u2212")
    return str(x)


def _is_p_column(name) -> bool:
    """Columns of p-values: headed "p" or "$p$", possibly followed by a qualifier such as "(perm.)"."""
    return re.match(r"^\$?p\$?(\s|\(|$)", str(name)) is not None


def sci(x: float, nd: int = 1) -> str:
    """Scientific notation for TeX math mode: 2.9\\cdot 10^{6}."""
    m, e = f"{x:.{nd}e}".split("e")
    return f"{m.replace('-', chr(0x2212))}\\cdot 10^{{{int(e)}}}"


def grouped(x: float, nd: int = 1) -> str:
    """Thousands separated by thin spaces: 1\\,390\\,310.7 (large numbers whose digits matter)."""
    return f"{x:,.{nd}f}".replace(",", "\\,").replace("-", "\u2212")


def auto_fmt(x) -> str:
    """Floats: 1 decimal if |x| >= 10, 2 if |x| >= 1, otherwise 3 (p-values: 2 significant)."""
    if isinstance(x, (float, np.floating)) and np.isfinite(x):
        a = abs(x)
        if 0 < a < 0.001:
            return f"{x:.1e}".replace("e-0", "\\cdot 10^{-").replace("e-", "\\cdot 10^{-") + "}"
        return fmt(x, 1 if a >= 10 else 2 if a >= 1 else 3)
    return fmt(x)


def save_numbers(lab: str, numbers: dict, nd: int | None = None):
    """Write ``\\newcommand`` macros (e.g. \\LabOneTestRmse) and a JSON copy."""
    lines = [f"% generated by code/{lab}; do not edit"]
    for k, v in numbers.items():
        val = v if isinstance(v, str) else (fmt(v, nd) if nd is not None else auto_fmt(v))
        lines.append(f"\\newcommand{{\\{_macro_name(lab, k)}}}{{{val}}}")
    (C.GEN_DIR / f"{lab}_numbers.tex").write_text("\n".join(lines) + "\n")
    (C.RESULTS_DIR / f"{lab}_numbers.json").write_text(
        json.dumps({k: (float(v) if isinstance(v, (np.floating, float)) else
                        int(v) if isinstance(v, (np.integer, int)) else v)
                    for k, v in numbers.items()}, indent=1))


def _ragged(col_format: str) -> str:
    """Paragraph columns p{..} are set ragged right: justified text in narrow table cells leaves wide gaps."""
    return re.sub(r"(>\{[^{}]*\})?p\{", lambda m: m.group(0) if m.group(1) else ">{\\raggedright\\arraybackslash}p{",
                  col_format)


def _split_top(s: str) -> list[str]:
    """Split at spaces outside $...$ and {...}."""
    parts, cur, depth, math = [], "", 0, False
    for ch in s:
        if ch == "$":
            math = not math
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
        if ch == " " and depth == 0 and not math:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return [x for x in parts if x]


def _visible_len(s: str) -> int:
    return len(re.sub(r"\\[a-zA-Z]+|[{}$\\^_]", "", s))


def wrap_header(cell: str, min_len: int = 9) -> str:
    """A long column head becomes two centred lines (\\hd{..\\\\..}), split at the space nearest its middle.

    Tables are set at 13 pt without scaling (GSU rules 3.10); wrapped heads keep them within the page.
    """
    c = cell.strip()
    if c.startswith("\\hd{") or _visible_len(c) < min_len:
        return cell
    words = _split_top(c)
    if len(words) < 2:
        return cell
    half = _visible_len(c) / 2
    best = min(range(1, len(words)), key=lambda i: abs(_visible_len(" ".join(words[:i])) - half))
    return "\\hd{" + " ".join(words[:best]) + "\\\\" + " ".join(words[best:]) + "}"


def wrap_table_heads(tex: str) -> str:
    """Apply wrap_header to the head row (the row after \\toprule) of a generated tabular."""
    lines = tex.split("\n")
    for i, line in enumerate(lines[:-1]):
        if line.strip() == "\\toprule":
            row = lines[i + 1].rstrip()
            if row.endswith("\\\\"):
                lines[i + 1] = " & ".join(wrap_header(c.strip()) for c in row[:-2].split(" & ")) + " \\\\"
            break
    return "\n".join(lines)


def save_table(name: str, df: pd.DataFrame, nd: int | dict = 3, index: bool = True,
               col_format: str | None = None, header: list[str] | None = None):
    """Booktabs ``tabular`` body for \\input inside a table environment."""
    d = df.copy()
    cols = list(d.columns)
    for c in cols:
        k = nd[c] if isinstance(nd, dict) and c in nd else (nd if isinstance(nd, int) else 3)
        if _is_p_column(c):
            d[c] = ["$<0.001$" if isinstance(v, (float, np.floating)) and 0 <= v < 0.0005 else fmt(v, k) for v in d[c]]
        else:
            d[c] = [fmt(v, k) for v in d[c]]
    if index:
        d.insert(0, d.index.name or "", d.index.astype(str))
    hdr = header or list(d.columns)
    if col_format is None:
        col_format = ("l" if index else "") + "c" * len(cols)
    col_format = _ragged(col_format)
    esc = lambda s: (str(s).replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")
                     .replace("^", "\\textasciicircum{}").replace("#", "\\#"))
    out = [f"\\begin{{tabular}}{{{col_format}}}", "\\toprule",
           " & ".join(wrap_header(esc(h) if "\\" not in str(h) and "$" not in str(h) else str(h))
                      for h in hdr) + " \\\\", "\\hdrule"]
    for _, row in d.iterrows():
        out.append(" & ".join(str(v) if ("$" in str(v) or "\\" in str(v)) else esc(v)
                              for v in row) + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    (C.GEN_DIR / f"{name}.tex").write_text("\n".join(out) + "\n")
    d.to_csv(C.RESULTS_DIR / f"{name}.csv", index=False)
